INSERT INTO dw.dim_date (
    date_key, full_date, day_of_month, month_number, month_name,
    quarter_number, year_number, day_of_week_number, day_name, is_weekend
)
SELECT
    TO_CHAR(d::date, 'YYYYMMDD')::INTEGER,
    d::date,
    EXTRACT(DAY FROM d)::SMALLINT,
    EXTRACT(MONTH FROM d)::SMALLINT,
    TO_CHAR(d, 'FMMonth'),
    EXTRACT(QUARTER FROM d)::SMALLINT,
    EXTRACT(YEAR FROM d)::SMALLINT,
    EXTRACT(ISODOW FROM d)::SMALLINT,
    TO_CHAR(d, 'FMDay'),
    EXTRACT(ISODOW FROM d) IN (6, 7)
FROM GENERATE_SERIES(DATE '2020-01-01', DATE '2030-12-31', INTERVAL '1 day') AS g(d)
ON CONFLICT (date_key) DO NOTHING;


